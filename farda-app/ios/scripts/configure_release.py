#!/usr/bin/env python3
"""Validate external iOS release inputs and emit ephemeral Xcode export files."""

from __future__ import annotations

import argparse
import os
from pathlib import Path
import plistlib
import re
import sys


REQUIRED = (
    "FARDA_IOS_APP_BUNDLE_ID",
    "FARDA_IOS_EXTENSION_BUNDLE_ID",
    "FARDA_IOS_TEAM_ID",
    "FARDA_IOS_APP_PROFILE",
    "FARDA_IOS_EXTENSION_PROFILE",
    "FARDA_IOS_EXPORT_METHOD",
    "FARDA_RELEASE_COMMIT",
    "FARDA_BUILD_NUMBER",
    "FARDA_VERSION_NAME",
)
EXPORT_METHODS = {"app-store-connect", "ad-hoc", "enterprise"}
BUNDLE_ID = re.compile(r"[A-Za-z][A-Za-z0-9-]*(\.[A-Za-z][A-Za-z0-9-]*)+")
MARKETING_VERSION = re.compile(
    r"(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)"
)
APPLE_BUILD_VERSION = re.compile(
    r"[1-9][0-9]{0,3}(\.(0|[1-9][0-9]?))?(\.(0|[1-9][0-9]?))?"
)
PLAY_MAX_VERSION_CODE = 2_100_000_000


def validate_release_versions(
    version_name: str, ios_build_number: str, android_version_code: str
) -> None:
    if not MARKETING_VERSION.fullmatch(version_name):
        raise ValueError(
            "version_name must contain three dot-separated numeric components without leading zeros"
        )
    if not APPLE_BUILD_VERSION.fullmatch(ios_build_number):
        raise ValueError(
            "ios_build_number must be a nonzero Apple bundle version with up to 4.2.2 digits"
        )
    if not re.fullmatch(r"[1-9][0-9]*", android_version_code):
        raise ValueError("android_version_code must be a positive integer")
    if int(android_version_code) > PLAY_MAX_VERSION_CODE:
        raise ValueError(
            f"android_version_code must not exceed {PLAY_MAX_VERSION_CODE}"
        )


def validated_environment(environ: dict[str, str]) -> dict[str, str]:
    values = {name: environ.get(name, "").strip() for name in REQUIRED}
    missing = [name for name, value in values.items() if not value]
    if missing:
        raise ValueError(f"Missing required iOS release settings: {', '.join(missing)}")

    app_id = values["FARDA_IOS_APP_BUNDLE_ID"]
    extension_id = values["FARDA_IOS_EXTENSION_BUNDLE_ID"]
    if not BUNDLE_ID.fullmatch(app_id) or app_id.startswith("com.example."):
        raise ValueError("FARDA_IOS_APP_BUNDLE_ID must be an approved non-placeholder bundle ID")
    if not BUNDLE_ID.fullmatch(extension_id) or not extension_id.startswith(f"{app_id}."):
        raise ValueError("FARDA_IOS_EXTENSION_BUNDLE_ID must be a child of the app bundle ID")
    if not re.fullmatch(r"[A-Z0-9]{10}", values["FARDA_IOS_TEAM_ID"]):
        raise ValueError("FARDA_IOS_TEAM_ID must be a 10-character Apple team ID")
    if values["FARDA_IOS_EXPORT_METHOD"] not in EXPORT_METHODS:
        raise ValueError(
            "FARDA_IOS_EXPORT_METHOD must be one of: " + ", ".join(sorted(EXPORT_METHODS))
        )
    if not re.fullmatch(r"[0-9a-f]{40}", values["FARDA_RELEASE_COMMIT"]):
        raise ValueError("FARDA_RELEASE_COMMIT must be an exact 40-character lowercase Git SHA")
    validate_release_versions(
        values["FARDA_VERSION_NAME"],
        values["FARDA_BUILD_NUMBER"],
        "1",  # Android has a separate workflow input and Gradle gate.
    )

    flutter_build_number = environ.get("FLUTTER_BUILD_NUMBER", "").strip()
    if flutter_build_number and flutter_build_number != values["FARDA_BUILD_NUMBER"]:
        raise ValueError("FLUTTER_BUILD_NUMBER does not match FARDA_BUILD_NUMBER")

    for name in ("FARDA_IOS_APP_PROFILE", "FARDA_IOS_EXTENSION_PROFILE"):
        value = values[name]
        if any(character in value for character in ("\n", "\r", "//", "/*", "*/")):
            raise ValueError(f"{name} contains characters unsafe for an xcconfig file")
    return values


def write_xcconfig(path: Path, values: dict[str, str]) -> None:
    keys = (
        "FARDA_IOS_APP_BUNDLE_ID",
        "FARDA_IOS_EXTENSION_BUNDLE_ID",
        "FARDA_IOS_TEAM_ID",
        "FARDA_IOS_APP_PROFILE",
        "FARDA_IOS_EXTENSION_PROFILE",
        "FARDA_RELEASE_COMMIT",
        "FARDA_BUILD_NUMBER",
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        "// Generated by ios/scripts/configure_release.py; do not commit.\n"
        + "".join(f"{key} = {values[key]}\n" for key in keys)
    )
    path.chmod(0o600)


def write_export_options(path: Path, values: dict[str, str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    options = {
        "destination": "export",
        "manageAppVersionAndBuildNumber": False,
        "method": values["FARDA_IOS_EXPORT_METHOD"],
        "provisioningProfiles": {
            values["FARDA_IOS_APP_BUNDLE_ID"]: values["FARDA_IOS_APP_PROFILE"],
            values["FARDA_IOS_EXTENSION_BUNDLE_ID"]: values["FARDA_IOS_EXTENSION_PROFILE"],
        },
        "signingCertificate": "Apple Distribution",
        "signingStyle": "manual",
        "stripSwiftSymbols": True,
        "teamID": values["FARDA_IOS_TEAM_ID"],
        "uploadSymbols": True,
    }
    with path.open("wb") as output:
        plistlib.dump(options, output, sort_keys=True)
    path.chmod(0o600)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="only validate the build environment")
    parser.add_argument("--validate-versions", action="store_true")
    parser.add_argument("--version-name")
    parser.add_argument("--ios-build-number")
    parser.add_argument("--android-version-code")
    parser.add_argument("--xcconfig", type=Path)
    parser.add_argument("--export-options", type=Path)
    args = parser.parse_args()
    if args.validate_versions:
        try:
            validate_release_versions(
                args.version_name or "",
                args.ios_build_number or "",
                args.android_version_code or "",
            )
        except ValueError as error:
            print(f"error: {error}", file=sys.stderr)
            return 2
        return 0
    if not args.check and (args.xcconfig is None or args.export_options is None):
        parser.error("generation requires --xcconfig and --export-options")

    try:
        values = validated_environment(dict(os.environ))
        if not args.check:
            write_xcconfig(args.xcconfig, values)
            write_export_options(args.export_options, values)
    except ValueError as error:
        print(f"error: {error}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
